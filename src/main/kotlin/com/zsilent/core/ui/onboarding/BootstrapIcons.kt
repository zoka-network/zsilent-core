/**
 * Tiny adapter that lets us embed Bootstrap Icons (https://icons.getbootstrap.com)
 * by pasting their raw SVG path data — no extra dependency. The icons are
 * rendered as Compose [ImageVector]s in the canonical 16×16 viewport bootstrap
 * uses, so dimensions stay accurate regardless of the host Icon size.
 *
 * To add a new icon: copy the `<path .../>` strings from a bootstrap icon SVG
 * and pass them to [bootstrapIcon] in the order they appear in the original.
 */
private fun bootstrapIcon(vararg paths: String): ImageVector {
    val builder = ImageVector.Builder(
        name = "bi",
        defaultWidth = 16.dp,
        defaultHeight = 16.dp,
        viewportWidth = 16f,
        viewportHeight = 16f
    )
    for (p in paths) {
        val nodes = PathParser().parsePathString(p).toNodes()
        builder.addPath(pathData = nodes, fill = SolidColor(Color.White))
    }
    return builder.build()
}

